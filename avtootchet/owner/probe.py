def _same(a: float, b: float) -> bool:
    return abs(a - b) < 1.0


class Probe:
    def __init__(self, src: ComSource, d1: date, d2: date):
        self.src, self.d1, self.d2 = src, d1, d2
        self.conn = None
        self.lines: list[str] = []

    # ---------------------------------------------------------------- помощники
    def _s(self, v) -> str:
        """Значение 1С (ссылка, тип, перечисление) -> текст."""
        if v is None:
            return "—"
        try:
            text = str(self.conn.String(v))
        except Exception:  # noqa: BLE001
            text = str(v)
        return text or "(пусто)"

    def _rows(self, text: str, *cols: str) -> list[tuple]:
        start = datetime(self.d1.year, self.d1.month, self.d1.day)
        end = datetime(self.d2.year, self.d2.month, self.d2.day, 23, 59, 59)
        q = self.conn.NewObject("Запрос")
        q.Text, _ = inline_dates(text, {"Начало": start, "Конец": end})
        sel = q.Execute().Choose()
        out = []
        while sel.Next():
            out.append(tuple(getattr(sel, c) for c in cols))
        return out

    def _section(self, title: str, fn: Callable[[], list[str]]) -> None:
        self.lines.append("")
        self.lines.append(f"== {title}")
        try:
            body = fn()
            self.lines.extend(body if body else ["(нет данных за период)"])
        except Exception as e:  # noqa: BLE001
            self.lines.append(f"ОШИБКА: {e}")

    # ---------------------------------------------------------------- проверки
    def registrars(self) -> list[str]:
        rows = self._rows(Q_REGISTRARS, "Касса", "Тип", "Движение", "Кол")
        return [f"{self._s(k)} | {self._s(t)} | {m}: {int(n)}"
                for k, t, m, n in sorted(rows, key=lambda r: (self._s(r[0]), self._s(r[1]), r[2]))]

    def basis(self, doc: str, field: str) -> list[str]:
        rows = self._rows(Q_BASIS.format(doc=doc, field=field), "Тип", "Вид", "Кол")
        return [f"основание: {self._s(t)} | вид операции: {self._s(v)}: {int(n)}" for t, v, n in rows]

    def breakdown(self) -> list[str]:
        rows = self._rows(Q_BREAKDOWN, "Тип", "Строк", "Док")
        return [f"{self._s(t)}: строк {int(r)}, документов {int(d)}" for t, r, d in rows]

    def orders(self) -> list[str]:
        rows = [tuple(float(x or 0) for x in r)
                for r in self._rows(Q_ORDERS, "Сумма", "Услуги", "Товары", "Материалы", "Оплачено", "Оплат")]
        if not rows:
            return []
        n = len(rows)
        c = Counter()
        for s, u, t, m, paid, cnt in rows:
            c["У+Т = сумма ЗН"] += _same(s, u + t)
            c["У+Т+М = сумма ЗН"] += _same(s, u + t + m)
            c["есть материалы"] += m > 0
            c["только работы"] += u > 0 and t == 0 and m == 0
            c["только запчасти"] += u == 0 and (t > 0 or m > 0)
            c["оплачен полностью"] += _same(paid, s)
            c["оплачен меньше суммы"] += paid < s - 1
            c["оплачен больше суммы"] += paid > s + 1
            c["несколько оплат"] += cnt > 1
        return [f"заказ-нарядов с оплатой в периоде: {n}"] + [f"{k}: {v} из {n}" for k, v in c.items()]

    def division(self) -> list[str]:
        rows = self._rows(Q_DIVISION, "Касса", "Подр", "Кол")
        return [f"{self._s(k)} | подразделение: {self._s(p)}: {int(n)}"
                for k, p, n in sorted(rows, key=lambda r: (self._s(r[0]), self._s(r[1])))]

    def order_types(self) -> list[str]:
        rows = self._rows(Q_ORDER_TYPES, "Тип", "Орг", "Кол")
        return [f"тип ЗН: {self._s(t)} | организация: {self._s(o)}: {int(n)}" for t, o, n in rows]

    def sales(self) -> list[str]:
        rows = self._rows(Q_SALES, "Вид", "Кол")
        return [f"вид операции: {self._s(v)}: {int(n)}" for v, n in rows]

    def groups(self) -> list[str]:
        rows = self._rows(Q_GROUPS, "Родитель", "Имя")
        return [f"{p} / {i}" if p else f"{i}" for p, i in rows]

    def run(self) -> str:
        self.src._check_settings()
        self.conn = self.src._connect()
        self.lines = [f"Структура Далиона за {self.d1:%d.%m.%Y}–{self.d2:%d.%m.%Y}",
                      "Только количества и названия, без сумм и клиентов."]
        self._section("1. Движения по кассам: касса | документ | приход/расход: количество",
                      self.registrars)
        self._section("2. Приходы (ПКО): на основании чего (ДокументОснование)",
                      lambda: self.basis("ПриходДенег", "ДокументОснование"))
        self._section("3. Приходы (ПКО): реквизит «Основание»",
                      lambda: self.basis("ПриходДенег", "Основание"))
        self._section("4. Приходы: расшифровка платежа (ДокОснование)", self.breakdown)
        self._section("5. Расходы (РКО, возвраты): на основании чего",
                      lambda: self.basis("РасходДенег", "ДокументОснование"))
        self._section("6. Заказ-наряды, оплаченные в периоде: сходятся ли суммы", self.orders)
        self._section("7. Приходы по кассам и подразделениям", self.division)
        self._section("8. Заказ-наряды по типу и организации", self.order_types)
        self._section("9. Расходные накладные по виду операции", self.sales)
        self._section("10. Группы номенклатуры (два уровня)", self.groups)
        return "\n".join(self.lines)


def run_probe(src: ComSource, days: int = 31) -> str:
    if not isinstance(src, ComSource):
        raise SourceError("Проверка структуры работает только с 1С:Далион через COM")
    d2 = date.today()
    return Probe(src, d2 - timedelta(days=days - 1), d2).run()
