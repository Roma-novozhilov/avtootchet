def _merge(saved, known: list[str]) -> list[list]:
    out, seen = [], set()
    for item in saved or []:
        try:
            name, on = str(item[0]), bool(item[1])
        except (TypeError, IndexError, ValueError):
            continue
        if name in known and name not in seen:
            out.append([name, on])
            seen.add(name)
    out += [[n, True] for n in known if n not in seen]
    return out


def default_layout() -> dict:
    return {"sheets": [[n, True] for n in SHEETS],
            "columns": {t: [[c, True] for c in cols] for t, cols in COLUMN_TABLES.items()}}


def normalize(layout: dict | None) -> dict:
    layout = layout or {}
    cols = layout.get("columns") or {}
    return {"sheets": _merge(layout.get("sheets"), SHEETS),
            "columns": {t: _merge(cols.get(t), known) for t, known in COLUMN_TABLES.items()}}


def enabled_sheets(layout: dict | None) -> list[str]:
    return [n for n, on in normalize(layout)["sheets"] if on]


def enabled_columns(layout: dict | None, sheet: str) -> list[str]:
    """Колонки листа по порядку; лист без настройки колонок - пустой список (все как есть)."""
    table = COLUMNS_OF_SHEET.get(sheet)
    if not table:
        return []
    return [c for c, on in normalize(layout)["columns"][table] if on]


def select(headers: list[str], rows: list[list], widths: list[int], chosen: list[str]):
    """Оставить в таблице только выбранные колонки в выбранном порядке."""
    if not chosen:
        return headers, rows, widths
    idx = [headers.index(c) for c in chosen if c in headers]
    if not idx:
        return headers, rows, widths
    return ([headers[i] for i in idx], [[r[i] for i in idx] for r in rows], [widths[i] for i in idx])
